def _with_documents_removed_in_9_0_0(policy):
    """`policy` with the document maps, floors and rules 9.0.0 removed put back, when it
    holds none of them; a policy that holds any of them is returned as it is."""
    shapes = policy.get("route_shapes")
    guard = policy.get("routing_guardrails")
    if not isinstance(shapes, dict) or not isinstance(guard, dict) \
            or not isinstance(guard.get("floors"), list):
        return policy
    floor_ids = [rule.get("id") for rule in guard["floors"] if isinstance(rule, dict)]
    if any((shape or {}).get("artifacts") for shape in shapes.values()) \
            or guard.get("artifact_rules") or guard.get("role_rules") \
            or any(rule["id"] in floor_ids for rule in REMOVED_DOCUMENT_FLOORS_9_0_0) \
            or "RP-REQUIRE-004" not in floor_ids:
        return policy
    policy = copy.deepcopy(policy)
    for name, documents in REMOVED_DOCUMENT_MAPS_9_0_0.items():
        if name in policy["route_shapes"]:
            policy["route_shapes"][name]["artifacts"] = dict(documents)
    floors = policy["routing_guardrails"]["floors"]
    at = [rule.get("id") for rule in floors].index("RP-REQUIRE-004") + 1
    floors[at:at] = copy.deepcopy(list(REMOVED_DOCUMENT_FLOORS_9_0_0))
    policy["routing_guardrails"]["artifact_rules"] = copy.deepcopy(
        list(REMOVED_DOCUMENT_RULES_9_0_0))
    return policy


def as_recorded_before_9_0_0(out, assessment, policy):
    """`out`, one result of `compact`, with what 9.0.0 stopped routing put back in the
    shape 5.6.0 recorded it: the rules of `REMOVED_RULES_9_0_0` that `policy` declares,
    that add `verify.analyze` and that match `assessment`, and their gate."""
    floors = (policy.get("routing_guardrails") or {}).get("floors") or []
    order = [rule.get("id") for rule in floors if isinstance(rule, dict)]
    removed = {rule["id"] for rule in REMOVED_RULES_9_0_0}
    fired = list(out["rules_fired"])
    added = False
    for rule in floors:
        if not isinstance(rule, dict) or rule.get("id") not in removed \
                or rule.get("add_gate") != REMOVED_GATE_9_0_0 \
                or not reading_matches(rule.get("when"), assessment,
                                       policy.get("dimension_orders")):
            continue
        before = order[:order.index(rule["id"])]
        at = max((i + 1 for i, rid in enumerate(fired) if rid in before), default=0)
        fired.insert(at, rule["id"])
        added = True
    out = dict(out, rules_fired=fired)
    if added and out["delivery_approach"] != "spike":
        out["gates"] = sorted(out["gates"] + [REMOVED_GATE_9_0_0])
    return out


# The baseline was captured at 5.6.0, before the depth words and the size were
# renamed (issue `vocabulary-and-cli-renames`), and is never regenerated. So a
# result is compared in the old words: the size an assessment names is read
# as the new word the evaluator expects, and the stage weights and artifact
# depths it returns are written back as the old words. This table is the one
# place the comparison knows the rename. A verdict that differs after the
# bridge has moved, and the test says which field.
SIZE_NOW = {"standard": "medium"}
DEPTH_WAS = {"thorough": "full", "lightweight": "light",
             "thorough-with-follow-up": "full-plus-backfill"}


def compact(readings, policy):
    """The fields the compatibility promise covers, for every autonomy
    setting, or the refusal text when the evaluator refuses."""
    out = {}
    policy = _with_documents_removed_in_9_0_0(_with_rules_removed_in_9_0_0(policy))
    readings, role = _role_as_documents(readings, policy)
    if "size" in readings:
        readings["size"] = SIZE_NOW.get(readings["size"], readings["size"])
    for autonomy in AUTONOMY:
        try:
            r = evaluate_route(copy.deepcopy(readings), policy, autonomy=autonomy)
        except CompassError as exc:
            return {"error": str(exc)}
        if not out:
            out = {
                "delivery_approach": r["delivery_approach"],
                "stages": {s: DEPTH_WAS.get(m, m) for s, m in r["stages"].items()},
                "gates": sorted(r["gates"]),
                "artifacts": sorted((a["kind"], DEPTH_WAS.get(a["depth"], a["depth"]))
                                    for a in r["artifacts"]
                                    if not (a["kind"] in ADDED_TO_EVERY_APPROACH
                                            and r["delivery_approach"] != "quick-fix")
                                    and not (r["delivery_approach"] == "quick-fix"
                                            and a["kind"] in ADDED_TO_QUICK_FIX)
                                    and not (r["delivery_approach"] == "spike"
                                             and a["kind"] in ADDED_TO_SPIKE)
                                    and not (r["delivery_approach"] == "hotfix"
                                             and a["kind"] in ADDED_TO_HOTFIX)
                                    and not (r["delivery_approach"] == "regular"
                                             and a["kind"] in ADDED_TO_REGULAR
                                             and DEPTH_WAS.get(a["depth"]) == "light")),
                "subtask_ceiling": r["subtask_ceiling"],
                "required_artifacts": sorted(r["required_artifacts"]),
                "required_skills": sorted(SPELLED_AS_5_6_0_SKILL.get(s, s)
                                          for s in r["required_skills"]),
                "blocked_phases": r["blocked_phases"],
                "max_worktrees": r["max_worktrees"],
                "rules_fired": [f["id"] for f in r["policy_rules_fired"]],
                "checkpoints": {},
            }
            out = as_recorded_before_9_0_0(out, readings, policy)
        out["checkpoints"][autonomy] = r["checkpoints"]
    if role is not None or "role" not in (policy.get("assessment_vocabulary") or {}):
        out = _as_recorded_with_role(out, role)
    # Through JSON, so a tuple and a list compare alike after a round trip.
    return json.loads(json.dumps(out, sort_keys=True))


def digest(result):
    text = json.dumps(result, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def grid(vocabulary):
    """Every closed assessment, in a fixed order, with no labels. A dimension
    the vocabulary does not hold (role, from 7.0.0) is left out."""
    names = [d for d in DIMENSIONS if d in vocabulary]
    for values in itertools.product(*(vocabulary[d] for d in names)):
        readings = dict(zip(names, values))
        readings["labels"] = []
        yield readings


def label_subsets(labels):
    for n in range(len(labels) + 1):
        for subset in itertools.combinations(labels, n):
            yield list(subset)


def named_labels(policy):
    """Every label a routing predicate names: only these can change a result."""
    found = set()

    def walk(node):
        if isinstance(node, dict):
            for key, value in node.items():
                if key == "labels_any" and isinstance(value, list):
                    found.update(value)
                walk(value)
        elif isinstance(node, list):
            for item in node:
                walk(item)

    walk(policy)
    return sorted(found)


def load_routing():
    """The captured baseline: its header and its rows."""
    with gzip.open(ROUTING, "rt", encoding="utf-8") as fh:
        lines = [json.loads(line) for line in fh if line.strip()]
    return lines[0], lines[1:]


def legacy_spelling(result):
    """A routing result from the layered path, spelled as 5.6.0 spelled it.

    The shipped preset names a required document by its id (`intent`,
    `launch-readiness`) and a blocked stage by its current name (`ship`). The
    5.6.0 policy file named them `intent.md`, `launch-readiness.md` and `land`,
    and the generated view still does. This maps exactly those three names back
    and changes nothing else, so any other name still differs from the baseline
    and a layered result is compared with it field for field."""
    if "error" in result:
        return result
    out = dict(result)
    out["required_artifacts"] = sorted(
        SPELLED_AS_5_6_0_ARTIFACT.get(a, a) for a in result["required_artifacts"])
    out["blocked_phases"] = [
        dict(b, phase=SPELLED_AS_5_6_0_STAGE.get(b["phase"], b["phase"]))
        for b in result["blocked_phases"]]
    return out


SPELLED_AS_5_6_0_ARTIFACT = {"intent": "intent.md",
                             "launch-readiness": "launch-readiness.md"}
SPELLED_AS_5_6_0_STAGE = {"ship": "land"}
# The shipped policy names the skill in US English from 7.0.0; the baseline
# holds the 5.6.0 spelling. `compact` maps this one name back, so any other
# skill name still differs from the baseline.
SPELLED_AS_5_6_0_SKILL = {"behavior-mapping": "behaviour-mapping"}  # us-english-scan: allow - 5.6.0 baseline name


def routing_differences(policy, header, rows, first_only=False, layered=False):
    """Every place `policy` routes differently from the baseline, as text.
    Empty when the two agree everywhere the baseline recorded. With
    `first_only`, it stops at the first difference, which is all a test
    that plants a fault needs."""
    found = []
    labels = header["labels"]
    for row in rows:
        if row["kind"] in ("grid", "archive"):
            now = compact(row["assessment"], policy)
            if layered:
                now = legacy_spelling(now)
            if now != row["result"]:
                found.append(f"{row['kind']} {row['assessment']}: "
                             f"{_first_difference(row['result'], now)}")
                if first_only:
                    return found
        elif row["kind"] == "label-digests":
            assessment = row["assessment"]
            for subset, expected in zip(label_subsets(labels), row["digests"]):
                readings = dict(assessment, labels=subset)
                now = compact(readings, policy)
                if digest(legacy_spelling(now) if layered else now) != expected:
                    found.append(f"labels {subset} on {assessment}: result changed")
                    if first_only:
                        return found
    return found


def _first_difference(old, new):
    if "error" in old or "error" in new:
        return f"was {old.get('error', 'routed')!r}, now {new.get('error', 'routed')!r}"
    for key in sorted(set(old) | set(new)):
        if old.get(key) != new.get(key):
            return f"{key} was {old.get(key)!r}, now {new.get(key)!r}"
    return "no difference"


def owed_by_approach(rows):
    """Contract 2: for each delivery approach, every distinct combination of
    gates and artifacts it owes across the label-free grid."""
    owed = {}
    for row in rows:
        result = row.get("result") or {}
        if row["kind"] != "grid" or "error" in result:
            continue
        key = json.dumps({"gates": result["gates"], "artifacts": result["artifacts"]},
                         sort_keys=True)
        owed.setdefault(result["delivery_approach"], set()).add(key)
    return {approach: [json.loads(k) for k in sorted(keys)]
            for approach, keys in sorted(owed.items())}


