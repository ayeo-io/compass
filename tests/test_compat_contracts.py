"""The compatibility contracts: a project with no configuration behaves as
the release the configuration rewrite started from.

Each contract compares today's behaviour with a baseline captured once, at
5.6.0, by `scripts/capture-compat-baseline.py`. A baseline is never
regenerated by running new code: that would record a regression as the
expected result. Every contract also proves it can fail, by changing one
default in memory and expecting a difference.

Contracts 1 and 2 (routing output, and what each delivery approach owes)
live here now; the others join as they are captured. They read the 8.0.4
governance copy (`compat_baseline.policy_8_0_4`), the last release that routed
delivery approaches, in place of the live default. 9.0.0 replaces the
approaches with one path (ADR-092), so a change to the live default's
approaches does not move these two contracts. The tests of the two bridges that
put back what 9.0.0 removed from a policy read configuration B, the frozen
`default@6` preset, because the 8.0.4 copy still holds those parts and the
bridges leave it as it is.

Scenario id: `TRC-001` (issue `compat-routing-baseline`).
"""
from __future__ import annotations

import copy

import pytest
import yaml

from compat_baseline import (OWED, compact, grid,
                             load_routing, named_labels, owed_by_approach,
                             policy_8_0_4, policy_under, routing_differences)


@pytest.fixture(scope="module")
def policy_b(tmp_path_factory):
    """Configuration B's policy: the frozen `default@6` preset, which 9.0.0 reads
    without the gate, the rules and the documents it removed (ADR-091). The two
    bridges of `compat_baseline` put those back only in a policy that lacks them,
    so their tests read this one."""
    return policy_under("B", tmp_path_factory.mktemp("policy-B"))


# --- contract 1: routing output ------------------------------------------------

def test_contract_1_the_baseline_covers_the_whole_grid():
    header, rows = load_routing()
    assert header["version"] == "5.6.0" and header["captured_from"]
    vocabulary = header["vocabulary"]
    expected = [r for r in grid(vocabulary)]
    recorded = [r["assessment"] for r in rows if r["kind"] == "grid"]
    assert recorded == expected, "the baseline does not hold the whole grid"
    assert len(recorded) == 1200
    digests = [r for r in rows if r["kind"] == "label-digests"]
    assert len(digests) == 1200
    assert all(len(r["digests"]) == 2 ** len(header["labels"]) for r in digests)
    assert header["labels"] == ["auth", "migrations", "payments", "personal-data"]
    assert any(r["kind"] == "archive" for r in rows)


def test_contract_1_the_8_0_4_copy_routes_as_the_baseline():
    header, rows = load_routing()
    # From 7.0.0 the generated view spells documents and stages as the
    # catalogue does (ADR-070), so it is compared in the 5.6.0 spelling.
    differences = routing_differences(policy_8_0_4(), header, rows, layered=True)
    assert differences == [], "\n".join(differences[:10])


def test_contract_1_can_fail_when_one_default_changes():
    header, rows = load_routing()
    policy = policy_8_0_4()
    policy["route_shapes"]["regular"]["gates"] = [
        g for g in policy["route_shapes"]["regular"]["gates"] if g != "verify.regression"]
    assert routing_differences(policy, header, rows, first_only=True, layered=True), \
        "a dropped gate went unseen"


def test_contract_1_a_change_only_a_label_reaches_is_seen():
    # The label digests are the only record of label subsets; prove they bite.
    header, rows = load_routing()
    policy = policy_8_0_4()
    for rule in policy["routing_guardrails"]["floors"]:
        if "migrations" in str(rule.get("when")):
            rule["when"] = {"labels_any": ["nothing-matches"]}
    assert named_labels(policy_8_0_4()) == header["labels"]
    assert routing_differences(policy, header, rows, first_only=True, layered=True), \
        "a label-only change went unseen"


def _with_floor(policy, rule_id, **change):
    """`policy` with the two removed rules put back when it lacks them, with one
    floor changed (or dropped, when `change` is empty). The 8.0.4 copy still holds
    the two rules, so for it only the one floor changes."""
    from compat_baseline import _with_rules_removed_in_9_0_0
    policy = copy.deepcopy(_with_rules_removed_in_9_0_0(policy))
    floors = policy["routing_guardrails"]["floors"]
    at = next(i for i, rule in enumerate(floors) if rule.get("id") == rule_id)
    if change:
        floors[at] = dict(floors[at], **change)
    else:
        del floors[at]
    return policy


AUTH = {"risk": "contained", "familiarity": "brownfield-mapped", "size": "medium",
        "goal": "delivery", "urgency": "none", "role": "engineer", "labels": ["auth"]}


def test_contract_1_puts_back_the_gate_and_rules_9_0_0_removed_in_their_place(policy_b):
    """9.0.0 routes no `verify.analyze` (ADR-091). The comparison puts the gate and the
    rule that added it back where 5.6.0 recorded them, and nothing else."""
    import compat_baseline as cb
    from compass_pkg.routing import evaluate_route
    now = evaluate_route(dict(AUTH, labels=["auth"]),
                         cb._with_rules_removed_in_9_0_0(policy_b))
    assert "verify.analyze" not in now["gates"]
    out = compact(AUTH, policy_b)
    assert "verify.analyze" in out["gates"]
    fired = out["rules_fired"]
    assert fired.index("RP-REQUIRE-002") + 1 == fired.index("RP-REQUIRE-004"), fired
    assert "RP-REQUIRE-001" not in fired


def test_contract_1_still_sees_any_other_change_beside_the_removed_gate():
    header, rows = load_routing()
    # A rule beside the two removed ones is dropped.
    assert routing_differences(_with_floor(policy_8_0_4(), "RP-REQUIRE-004"),
                               header, rows, first_only=True, layered=True)
    # A removed rule that adds another gate is no longer the removed rule.
    assert routing_differences(
        _with_floor(policy_8_0_4(), "RP-REQUIRE-002", add_gate="verify.claims"),
        header, rows, first_only=True, layered=True)


def test_contract_1_sees_an_evaluator_that_routes_the_removed_gate_again(monkeypatch):
    """The comparison adds the gate and rule back without merging, so an evaluator
    that still routed them would record each twice, and differ."""
    from compass_pkg import routing
    monkeypatch.setattr(routing, "REMOVED_GATES", {})
    out = compact(AUTH, policy_8_0_4())
    assert out["rules_fired"].count("RP-REQUIRE-002") == 2, out["rules_fired"]
    assert out["gates"].count("verify.analyze") == 2, out["gates"]
    header, rows = load_routing()
    assert routing_differences(policy_8_0_4(), header, rows, first_only=True,
                               layered=True)


def test_contract_1_puts_back_the_documents_9_0_0_removed(policy_b):
    """9.0.0 owes no document (ADR-091). The comparison puts back the approach maps, the
    two floors and the two document rules 8.0.0 declared, and nothing else."""
    from compass_pkg.routing import evaluate_route
    now = evaluate_route(dict(AUTH), policy_b)
    assert now["artifacts"] == [] and now["required_artifacts"] == [], now["artifacts"]
    assert "RP-REQUIRE-005" not in [f["id"] for f in now["policy_rules_fired"]]
    out = compact(AUTH, policy_b)
    assert ["threat-model", "full"] in out["artifacts"], out["artifacts"]
    fired = out["rules_fired"]
    assert fired.index("RP-REQUIRE-004") + 1 == fired.index("RP-REQUIRE-005"), fired


def test_contract_1_still_sees_a_policy_that_owes_a_document_again(policy_b):
    """A policy that owes any document is compared as it is, so an approach map that
    came back would differ from the baseline."""
    header, rows = load_routing()
    policy = copy.deepcopy(policy_b)
    policy["route_shapes"]["regular"]["artifacts"] = {"technical-design": "thorough"}
    assert routing_differences(policy, header, rows, first_only=True, layered=True), \
        "a returned document map went unseen"


