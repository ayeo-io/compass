    assert differs(None, "nothing-to-check")
    assert archive_differences(*allow_7_0_0_moves(
        {"x": {"check_exit": 1, "verdicts": {"consistency-check-passes": "fail"}}},
        {"x": {"check_exit": 0, "verdicts": {}}}))


