def _rewrite_generation(task_dir, edit_versions, n=1):
    """Rewrite what generation `n` stored, and the marker's digest, as an earlier release
    would have stored it."""
    from compass_pkg.atomic_io import digest
    folder = Path(task_dir) / "generations" / str(n)
    marker = yaml.safe_load((folder / "complete").read_text("utf-8"))
    data = yaml.safe_load((folder / "versions.yml").read_text("utf-8"))
    edit_versions(data)
    (folder / "versions.yml").write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    marker["files"]["versions.yml"] = digest(data)
    (folder / "complete").write_text(yaml.safe_dump(marker, sort_keys=False), encoding="utf-8")


def _row(root, name):
    out = run(root, "check", "--issue", SLUG, "--json")[1]
    rows = [c for c in json.loads(out)["checks"] if c["name"] == name]
    return rows[0] if rows else None


def test_dcj_76_a_migrate_pins_a_generation_that_records_a_major_the_cli_lacks(tmp_path):
    # An issue in flight, and a done one: both are carried.
    for name, status in (("open", "in-progress"), ("closed", "done")):
        root = _done_issue(tmp_path / name, MARKS, status=status)
        task_dir = Path(root) / WORK
        _rewrite_generation(task_dir, lambda d: d["implementations"].update(
            {"dod-evidence-typed": "1.0.0"}))
        refused = _row(root, "dod-evidence-typed")
        assert refused["status"] == "refused", refused
        code, out, err = _apply(root)
        assert code == 0, out + err
        assert "dod-evidence-typed" in out and "generation" in out, out
        assert manifest(root)["generation"] == 2, manifest(root)["generation"]
        versions = yaml.safe_load((task_dir / "generations" / "2" / "versions.yml").read_text())
        assert versions["implementations"]["dod-evidence-typed"].startswith("2."), versions
        assert render(root)[0] == 0
        row = _row(root, "dod-evidence-typed")
        assert row["status"] != "refused", row
        # A second apply pins nothing.
        again = _apply(root)
        assert again[0] == 0 and "generation" not in again[1], again
        assert manifest(root)["generation"] == 2
    # An issue whose generation records only majors the CLI has is not re-pinned.
    root = _done_issue(tmp_path / "current", MARKS, status="in-progress")
    code, out, err = _apply(root)
    assert code == 0, out + err
    assert manifest(root)["generation"] == 1
    assert "pinned" not in out


# --- DCJ-82 (approved 2026-10-11: dod-evidence-typed and a closed issue with no list) -------

def _dod_row(root):
    return _row(root, "dod-evidence-typed")


def test_dcj_82_closed_issue_with_no_definition_of_done_section_has_nothing_to_check(tmp_path):
    """The shape of four archived issues: a verification report with no Definition of Done
    heading and no dod block. A closed issue reads nothing to check; an issue in flight is still
    judged, so deleting the section does not clear the check."""
    closed = _done_issue(tmp_path / "closed", [], heading=None, evidence=False)
    row = _dod_row(closed)
    assert row["status"] == "nothing-to-check", row
    assert "no Definition of Done" in row["detail"], row
    flight = _done_issue(tmp_path / "flight", [], heading=None, evidence=False,
                         status="in-progress")
    assert _dod_row(flight)["status"] == "fail", _dod_row(flight)
    # A closed issue that does have the heading is judged: its items are open.
    listed = _done_issue(tmp_path / "listed", [], evidence=False)
    assert _dod_row(listed)["status"] == "fail", _dod_row(listed)
    # A closed issue whose report holds a dod block but no heading is judged too.
    block = _done_issue(tmp_path / "block", [], heading=None, evidence=False)
    path = doc_path(block, "verification-report")
    path.write_text(path.read_text("utf-8") + PAIR, encoding="utf-8")
    assert _dod_row(block)["status"] == "fail", _dod_row(block)
