def test_dcj_11_a_migrated_approved_report_stays_approved(tmp_path):
    root = _done_issue(tmp_path, ["x"] * 7)
    recorded = _entry(root, "verification-report")["digest"]
    code, out, err = _apply(root)
    assert code == 0, out + err
    assert PAIR in doc_path(root, "verification-report").read_text("utf-8")
    after = _entry(root, "verification-report")
    assert after["status"] == "approved" and after["approved_by"] == "jed72"
    assert after["digest"] != recorded, "the digest of the masked text moves with the marker lines"
    code, out, err = sup.register(root, "verification-report", "draft")
    assert code == 0, out + err
    again = _entry(root, "verification-report")
    assert again["status"] == "approved" and again["approved_at"] == "2026-10-10T12:00:00Z"
    assert again["digest"] == after["digest"]


# --- DCJ-80 -----------------------------------------------------------------

def test_dcj_80_page_tick_never_counts_as_approval(tmp_path):
    """The check fails for the critical issue still in flight, and reports only for the one that
    has closed (it cleared its gates under the trigger in force); a page tick changes neither."""
    for state, word in (("in-progress", "fail"), ("done", "pass")):
        root = _done_issue(tmp_path / state, ["x"] * 7, evidence=False, status=state,
                           assessment={"risk": "critical", "labels": ["migrations"]})

        def report():
            done = run(root, "check", "--issue", SLUG, "--json")
            assert done[1].strip().startswith("{"), done[1] + done[2]
            return {c["name"]: c for c in json.loads(done[1])["checks"]}

        before = report()["human-approval-present"]
        assert before["status"] == word, before
        evidence_before = manifest(root).get("evidence")
        code, out, err = _apply(root)
        assert code == 0, out + err
        assert render(root)[0] == 0
        block = _dod_block(root).group(1).splitlines()
        assert block[0] == "Definition of Done: 7 of 7 met", block[0]
        assert sum("ticked on the page before 7.0.0" in line for line in block) == 7
        after = report()["human-approval-present"]
        assert after == before, (before, after)
        assert manifest(root).get("evidence") == evidence_before
        assert len(manifest(root)["page_ticks"]) == 7
    # No approval reader looks at a page tick.
    from compass_pkg import approval_records, checks
    for module in (approval_records, checks):
        assert "page_ticks" not in Path(module.__file__).read_text("utf-8"), module.__name__


