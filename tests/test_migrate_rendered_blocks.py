def test_dcj_66_dry_run_writes_nothing_second_apply_no_change(tmp_path):
    root = _done_issue(tmp_path, MARKS)
    _extra_issue(root, "fix-done", approach="quick-fix")
    _extra_issue(root, "old-page", readme=OLD_MARKER + "\n\n# generated\n")
    before = _tree(root)
    code, out, err = _migrate(root)
    assert code == 0, out + err
    for needle in (SLUG, "fix-done", "old-page", "item record", "marker", "verification note",
                   "README.md.v6.bak"):
        assert needle in out, (needle, out)
    assert re.search(r"7 item records", out), out
    assert "dry run" in out
    assert _tree(root) == before
    code, out, err = _apply(root)
    assert code == 0, out + err
    first = _tree(root)
    assert first != before
    code, out, err = _apply(root)
    assert code == 0, out + err
    assert "nothing to do" in out, out
    assert "migrated" not in out
    assert _tree(root) == first
    code, out, err = _migrate(root)
    assert "nothing to do" in out and "would" not in out, out
    assert _tree(root) == first


