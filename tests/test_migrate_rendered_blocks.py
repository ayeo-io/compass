def test_dcj_65_migrate_writes_notes_removes_old_pages(tmp_path):
    root = _done_issue(tmp_path, ["x"] * 7)
    done_fix = _extra_issue(root, "fix-done", approach="quick-fix")
    skipped_fix = _extra_issue(root, "fix-skipped", approach="quick-fix",
                               close_reason="not-planned")
    generated = OLD_MARKER + "\n\n# generated\n"
    appended = OLD_MARKER + "\n\n# generated\n\nA paragraph a person wrote under it.\n"
    handwritten = "# My own notes\n\nNo marker here.\n"
    old = _extra_issue(root, "old-page", readme=generated)
    appends = _extra_issue(root, "appended-page", readme=appended)
    mine = _extra_issue(root, "my-page", readme=handwritten)
    del done_fix, skipped_fix

    code, out, err = _apply(root)
    assert code == 0, out + err

    note = Path(root) / "docs/compass/2026-10-10-fix-done/verification-note.md"
    assert note.is_file()
    assert note.read_text("utf-8").count("<!-- compass:render verification-note -->") == 1
    parts = note.read_text("utf-8").split("<!-- compass:render verification-note -->\n")
    assert parts[1] == "<!-- /compass:render -->\n"
    registered = _entry(root, "verification-note", "fix-done")
    assert registered["path"] == "docs/compass/2026-10-10-fix-done/verification-note.md"
    assert not (Path(root) / "docs/compass/2026-10-10-fix-skipped").exists()
    assert "artifacts" not in manifest(root, "fix-skipped")
    # The old generated pages are kept byte for byte under the new name.
    for folder, text in ((old, generated), (appends, appended)):
        assert not (folder / "README.md").exists()
        assert (folder / "README.md.v6.bak").read_text("utf-8") == text
    assert (mine / "README.md").read_text("utf-8") == handwritten
    assert not (mine / "README.md.v6.bak").exists()
    # The migration output names what it renamed aside.
    assert "README.md.v6.bak" in out and "old-page" in out and "appended-page" in out


