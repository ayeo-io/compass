OLD_MARKER = "<!-- GENERATED by `compass issue dashboard` - do not edit. Regenerate after any stage. -->"
PAIR = "<!-- compass:render dod -->\n<!-- /compass:render -->\n"

#: The statements of the shipped Definition of Done, in order, so a report reads as one
#: written from the template.
ITEMS = [
    "**Every scenario passes** - §1 is all PASS; the spec, read as the acceptance suite, is green.",
    "**TDD suite green** - §2 links the record of the full suite passing.",
    "**Coverage meets the \"Tested before it lands\" guardrail's floor (`G1`)** - evidence in §2.",
    "**No lint / format / type errors** - clean, with the record linked.",
    "**Traceability intact** - code → scenario → intent holds.",
    "*(carried to ship)* Living docs updated to match reality.",
    "*(carried to ship)* Every outstanding follow-up settled.",
]


def _report(marks, heading="### Definition of Done"):
    """A verification report whose Definition of Done holds one box per mark. A mark is
    `x` (ticked) or a tag such as `(evidence: EV-1)`."""
    lines = ["# Verification report", "", "Some prose.", "", "## Gate", "",
             "- [ ] A box above the Definition of Done that migration must not read.", ""]
    if heading:
        lines += [heading, "", "<!-- A comment that quotes a box:",
                  "- [ ] (evidence: EV-NOPE) not a real box", "-->", ""]
    for mark, item in zip(marks, ITEMS):
        lines.append("- [x] %s" % item if mark == "x" else "- [ ] %s %s" % (mark, item))
    lines += ["", "Next stage: **ship**", ""]
    return "\n".join(lines)


def _digest_of(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _write_manifest(root, body, slug=SLUG):
    manifest_file(root, slug).write_text(yaml.safe_dump(body, sort_keys=False), encoding="utf-8")


def _done_issue(tmp_path, marks, *, assessment=None, heading="### Definition of Done",
                evidence=True, status="done", approve=True):
    """The `feature` issue, closed as completed, with a report holding `marks`."""
    root = sup.project(tmp_path, assessment=assessment)
    body = manifest(root)
    body["status"] = status
    if status == "done":
        body["close_reason"] = "completed"
    body["current_phase"] = None
    if evidence:
        body["evidence"] = [
            {"id": "EV-1", "type": "test-run", "path": "evidence/green-1.json"},
            {"id": "EV-2", "type": "command-output", "path": "evidence/out.txt"},
            {"id": "EV-LOG", "type": "note", "path": "evidence/note.txt"}]
        body["follow_ups"] = [
            {"id": "FU-R", "status": "resolved", "summary": "Fixed the first thing"},
            {"id": "FU-O1", "status": "outstanding", "summary": "Do the second thing",
             "target_task": "other-issue"},
            {"id": "FU-O2", "status": "outstanding", "summary": "Do the third thing",
             "target_task": "other-issue"}]
    _write_manifest(root, body)
    write_doc(root, "verification-report", _report(marks, heading), register_it=True)
    assert sup.register(root, "verification-report", "draft")[0] == 0
    if approve:
        body = manifest(root)
        for entry in body["artifacts"]:
            if entry["kind"] == "verification-report":
                entry.update(status="approved", approved_by="jed72",
                             approved_at="2026-10-10T12:00:00Z")
        _write_manifest(root, body)
    return root


def _work(root):
    return str(Path(root) / ".compass" / "work")


def _migrate(root, *extra):
    return run(root, "issue", "migrate", _work(root), *extra)


def _apply(root):
    return _migrate(root, "--apply", "--i-have-a-copy")


def _entry(root, kind, slug=SLUG):
    return next(a for a in manifest(root, slug)["artifacts"] if a["kind"] == kind)


def _tree(root):
    """Every file of the work root and the documents folder with its digest, and the
    skip state the render keeps."""
    found = {}
    for top in (Path(root) / ".compass" / "work", Path(root) / "docs"):
        for path in sorted(top.rglob("*")):
            if path.is_file() and path.name not in (".render.lock", ".manifest.lock"):
                found[str(path.relative_to(root))] = _digest_of(path)
    return found


def _extra_issue(root, slug, *, report=None, status="done", approach=None, readme=None,
                 close_reason="completed", evidence=(), follow_ups=(), created="2026-10-10"):
    """Another issue in the work root, written by hand: a manifest, and with `report` a
    registered verification report in the documents folder."""
    folder = Path(root) / ".compass" / "work" / slug
    folder.mkdir(parents=True)
    body = {"schema_version": "2.0", "issue": slug, "created": created, "status": status}
    if status == "done":
        body["close_reason"] = close_reason
    if approach:
        body["delivery_approach"] = approach
    if evidence:
        body["evidence"] = list(evidence)
    if follow_ups:
        body["follow_ups"] = list(follow_ups)
    if report is not None:
        docs = Path(root) / "docs" / "compass" / f"{created}-{slug}"
        docs.mkdir(parents=True)
        (docs / "verification-report.md").write_text(report, encoding="utf-8")
        body["artifacts"] = [{"id": "ART-VERIFICATION_REPORT", "kind": "verification-report",
                              "status": "draft",
                              "path": f"docs/compass/{created}-{slug}/verification-report.md"}]
    (folder / "manifest.yml").write_text(yaml.safe_dump(body, sort_keys=False), encoding="utf-8")
    if readme is not None:
        (folder / "README.md").write_text(readme, encoding="utf-8")
    return folder


def _dod_block(root, slug=SLUG):
    text = doc_path(root, "verification-report").read_text("utf-8") if slug == SLUG else ""
    return re.search(r"<!-- compass:render dod -->\n(.*?)<!-- /compass:render -->", text, re.S)


