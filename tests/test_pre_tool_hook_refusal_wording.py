def test_bad_session_issue_in_own_project_tells_the_person_to_restart(tmp_path):
    """Scenario id: `TRC-020` in hooks-comment-only-edits-and-prose/acceptance-criteria.md"""
    root = _project(tmp_path, pointer="issue-a")
    r = _edit_code(root, issue="nope")

    assert r.returncode == 2, r.stderr
    assert r.stderr.rstrip().endswith("[bad-session-issue-restart]"), r.stderr
    fix = " ".join(_fix_line(r).split())
    assert "restart the session" in fix, fix
    assert "COMPASS_ISSUE" in fix and "existing issue" in fix, fix
    # A running session cannot change its environment.
    assert "set COMPASS_ISSUE" not in fix and "unset" not in fix, fix


def _linked_worktree(main):
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    git = ["git", "-c", "user.name=t", "-c", "user.email=t@example.com",
           "-c", "commit.gpgsign=false"]
    for args in (["init", "-q"], ["add", "cli"],
                 ["commit", "-q", "-m", "first"]):
        subprocess.run([*git, *args], cwd=str(main), check=True,
                       capture_output=True, text=True, env=env)
    wt = main.parent / "wt"
    subprocess.run([*git, "worktree", "add", "-q", "--detach", str(wt)],
                   cwd=str(main), check=True, capture_output=True, text=True,
                   env=env)
    return wt.resolve()


def test_bad_session_issue_in_a_worktree_names_compass_issue_use(tmp_path):
    """Scenario id: `TRC-021` in hooks-comment-only-edits-and-prose/acceptance-criteria.md"""
    main = _project(tmp_path, pointer="issue-a")
    wt = _linked_worktree(main)
    _issue(wt, "gamma", red=False)
    (wt / ".compass" / "current-task").write_text("\n")
    r = _edit_code(main, target=wt / "cli" / "compass_pkg" / "routing.py")

    assert r.returncode == 2, r.stderr
    assert r.stderr.rstrip().endswith("[bad-session-issue]"), r.stderr
    fix = " ".join(_fix_line(r).split())
    assert "compass issue use <slug>" in fix, fix
    assert "worktree" in fix, fix
    # The own-project advice does not apply to a worktree and has its own code.
    assert "COMPASS_ISSUE" not in fix, fix
