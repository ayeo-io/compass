"""The refusals and warnings of the pre-tool hook say what is true.

Three messages gave advice that does not work, or a cause that is not the real
one:

- `no-red-on-record` did not name `compass acceptance start`, the way out when
  no test fits the change.
- The warning for a `.compass/current-task` that names a missing issue said
  there was no pointer.
- `bad-session-issue` told the person to run `compass issue use`, which changes
  nothing in the session's own project, where `COMPASS_ISSUE` outranks the
  pointer. The own-project cause now has its own code, `bad-session-issue-restart`.

The hook is run for real, as `tests/test_worktree_issue_precedence.py` runs it.

Scenario ids: see hooks-comment-only-edits-and-prose/acceptance-criteria.md.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from test_session_issue import _issue

ROOT = Path(__file__).resolve().parent.parent
HOOK = ROOT / "hooks" / "pre-tool.sh"
CLI = ROOT / "cli" / "compass"

sys.path.insert(0, str(ROOT / "cli"))
from compass_pkg.refusals import render  # noqa: E402


def _project(tmp_path, *, issues=("issue-a",), pointer=None):
    """A project with the named issues, none with a failing test on record,
    and a production file to edit."""
    root = tmp_path / "proj"
    (root / "cli" / "compass_pkg").mkdir(parents=True)
    (root / "cli" / "compass_pkg" / "routing.py").write_text(
        "def route(issue):\n    return issue.slug\n", encoding="utf-8")
    for slug in issues:
        _issue(root, slug, red=False)
    if pointer is not None:
        (root / ".compass" / "current-task").write_text(pointer + "\n")
    return root


def _edit_code(root, *, issue=None, cwd=None, target=None):
    """An Edit that changes a line of code. The text of the file is not read by
    these scenarios: a code change is never a comment-only edit."""
    target = target or root / "cli" / "compass_pkg" / "routing.py"
    payload = {"tool_name": "Edit", "tool_input": {
        "file_path": str(target), "old_string": "return issue.slug",
        "new_string": "return issue.name"}}
    env = {k: v for k, v in os.environ.items()
           if k not in ("COMPASS_ISSUE", "CLAUDE_CODE_SESSION_ID")
           and not k.startswith("GIT_")}
    env["CLAUDE_PROJECT_DIR"] = str(root)
    if issue is not None:
        env["COMPASS_ISSUE"] = issue
    return subprocess.run(["bash", str(HOOK)], input=json.dumps(payload),
                          capture_output=True, text=True, env=env,
                          cwd=str(cwd or root), timeout=60)


def _fix_line(result):
    lines = [line for line in result.stderr.splitlines()
             if line.startswith("Fix:")]
    assert len(lines) == 1, result.stderr
    return lines[0]


def test_no_red_refusal_names_tdd_red_and_acceptance_start(tmp_path):
    """Scenario id: `TRC-014` in hooks-comment-only-edits-and-prose/acceptance-criteria.md"""
    root = _project(tmp_path, pointer="issue-a")
    r = _edit_code(root)

    assert r.returncode == 2, r.stderr
    fix = _fix_line(r)
    assert "compass tdd-red" in fix, fix
    assert "compass acceptance start" in fix, fix
    assert r.stderr.rstrip().endswith("[no-red-on-record]"), r.stderr


def test_changed_refusals_stay_under_sixty_words():
    """Scenario id: `TRC-015` in hooks-comment-only-edits-and-prose/acceptance-criteria.md

    The longest form: a 40-character slug and a guard of 20 words, which is the
    most the registry keeps of a long parameter."""
    slug = "a" * 40
    guard = " ".join(f"word{i}" for i in range(20))
    forms = {
        "no-red-on-record": dict(slug=slug, target="cli/compass_pkg/routing.py",
                                 tool="Edit", guard=guard),
        "bad-session-issue": dict(slug=slug, project="/work/" + "p" * 40),
        "bad-session-issue-restart": dict(slug=slug,
                                          project="/work/" + "p" * 40),
    }
    for code, params in forms.items():
        text = render(code, **params)
        assert len(text.split()) < 60, (code, len(text.split()), text)


def test_refusal_page_matches_the_registry():
    """Scenario id: `TRC-016` in hooks-comment-only-edits-and-prose/acceptance-criteria.md"""
    listing = subprocess.run([sys.executable, str(CLI), "_refusal", "--list"],
                             cwd=str(ROOT), capture_output=True, text=True,
                             timeout=30)
    assert listing.returncode == 0, listing.stderr
    page = (ROOT / "docs" / "refusal-codes.md").read_text(encoding="utf-8")
    marker = "<!-- generated by `compass _refusal --list` -->"
    assert page.split(marker, 1)[1].strip() == listing.stdout.strip()
    # The generated list holds the new wording, so a stale page cannot pass by
    # matching an old registry.
    assert "compass acceptance start" in listing.stdout
    assert "### `bad-session-issue-restart`" in listing.stdout


def test_pointer_to_a_missing_issue_says_the_issue_has_no_folder(tmp_path):
    """Scenario id: `TRC-017` in hooks-comment-only-edits-and-prose/acceptance-criteria.md"""
    root = _project(tmp_path, pointer="issue-zzz")
    r = _edit_code(root)

    warning = " ".join(r.stderr.split())
    assert ".compass/current-task names 'issue-zzz'" in warning, r.stderr
    assert "has no folder under .compass/work/" in warning, r.stderr
    assert "no .compass/current-task pointer" not in warning, r.stderr
    assert "falling back to the most recently modified issue (issue-a)" in warning
    assert "compass issue use <slug>" in warning, r.stderr


def test_pointer_to_a_missing_issue_is_still_judged_by_the_most_recent_issue(
        tmp_path):
    """Scenario id: `TRC-018` in hooks-comment-only-edits-and-prose/acceptance-criteria.md"""
